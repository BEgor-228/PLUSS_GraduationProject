    name, description, range_min, range_max, website, aoop_url, address,
    district_id, type_id, director_id, created_at, updated_at
)
SELECT
    c.name,
    c.description,
    c.range_min,
    c.range_max,
    c.website,
    NULL,
    c.address,
    d.id,
    'school',
    dir.id,
    NOW(),
    NOW()
FROM _chaplygin_schools_import c
CROSS JOIN mapapp_district d
LEFT JOIN mapapp_director dir ON dir.full_name = c.director_name
WHERE d.name = 'Чаплыгинский округ'
ON CONFLICT (name) DO NOTHING;

